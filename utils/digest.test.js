test('_renderEml produces a mime message with subject', () => {
  const digest = {
    title: 'Regress digest: 1 new case, 2 runs',
    recipients: ['qa@example.com'],
    html: '<html><body>hi</body></html>',
  };
  const eml = _renderEml(digest);
  assert.ok(eml.startsWith('From: Regress <no-reply@regress.local>'));
  assert.ok(eml.includes('\r\n\r\n'));
  assert.ok(eml.includes('To: qa@example.com'));
});

test('_renderEml encodes the entire subject in a single RFC 2047 token', () => {
  // Regression: the previous version of this file wrapped every non-ASCII
  // byte in its own `=?UTF-8?B??=` token, producing malformed output that
  // many MTAs bounced.
  const eml = _renderEml({ title: 'Café résumé — 5 cases', recipients: ['a@b.c'], html: 'x' });
  // Match exactly one subject line, with exactly one encoded word.
  const subjLine = eml.split('\r\n').find((l) => l.startsWith('Subject: '));
  const tokens = (subjLine.match(/\?=\s*\?=/g) || []).length;
  assert.equal(tokens, 0, 'subject must be a single RFC 2047 encoded word');
  // And the encoded form must decode back to the original (modulo CRLF).
  const m = subjLine.match(/^Subject: =\?UTF-8\?B\?(.+)\?=$/);
  assert.ok(m, `expected base64 RFC 2047 form, got: ${subjLine}`);
  assert.equal(Buffer.from(m[1], 'base64').toString('utf8'), 'Café résumé — 5 cases');
});

