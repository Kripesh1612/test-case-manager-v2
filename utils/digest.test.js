function makeFakePrisma(over = {}) {
  const counts = {
    testCase: { count: () => 1 },
    testRun: { count: () => 1 },
    ...over,
  };
  return {
    digestLog: {
      findFirst: async () => null,
      create: async ({ data }) => ({ id: 42, ...data }),
    },
    testCase: counts.testCase,
    testRun: counts.testRun,
  };
}

// ---- compose path (existing) ---------------------------------------------

test('composeDigest builds sections + title from fake counts', async () => {
  const db = makeFakePrisma({
    testCase: {
      count: async ({ where }) =>
        where.created_at && where.created_at.gte ? 3 : where.updated_at ? 2 : 9,
    },
    testRun: {
      count: async ({ where }) => (where.status === 'failed' ? 1 : where.status === 'errored' ? 0 : 5),
    },
  });

  const d = await composeDigest(1, { prisma: db, recipients: ['qa@example.com'] });
  assert.equal(d.project_id, 1);
  assert.equal(d.title, 'Regress digest: 3 new cases, 5 runs');
  const keys = d.sections.map((s) => s.key);
  assert.ok(keys.includes('new_cases'));
  assert.ok(keys.includes('changed_cases'));
  assert.ok(keys.includes('failures'));
  assert.ok(!keys.includes('errors'), 'zero-count eras should be filtered');
  assert.deepEqual(d.recipients, ['qa@example.com']);
  assert.ok(d.html.includes('Generated by Regress'));
});

test('composeDigest filters zero-count sections', async () => {
  const db = makeFakePrisma({
    testCase: { count: async () => 0 },
    testRun: { count: async () => 0 },
  });
  const d = await composeDigest(1, { prisma: db });
  assert.equal(d.sections.length, 0, 'quiet digest has no sections');
});

