// ---- SMTP client (Batch A audit fix A4) -----------------------------------

// Spin an in-process SMTP server that follows the protocol. The test
// can configure:
//   - `behavior.onCommand`: per-command hook to override responses (used
//     for the negative-path test that returns 5xx on EHLO).
//   - `received`: list of commands received, for assertions.
const startSmtpServer = (behavior = {}) => new Promise((resolve) => {
  const received = [];
  const server = net.createServer((sock) => {
    let buf = '';
    let inData = false;
    let dataBuf = '';
    sock.write('220 fake.test ESMTP ready\r\n');

    sock.on('data', (chunk) => {
      buf += chunk.toString('utf8');
      let nl;
      while ((nl = buf.indexOf('\r\n')) !== -1) {
        const line = buf.slice(0, nl);
        buf = buf.slice(nl + 2);
        if (inData) {
          if (line === '.') {
            inData = false;
            received.push({ cmd: 'DATA_BODY', body: dataBuf });
            dataBuf = '';
            const handler = (behavior.onCommand || {})['DATA_TERMINATOR'];
            sock.write(handler ? handler() : '250 OK message accepted\r\n');
          } else {
            // Reverse dot-stuffing for inspection.
            dataBuf += (line.startsWith('..') ? line.slice(1) : line) + '\r\n';
          }
          continue;
        }
        if (!line) continue;
        // Capture the command verb for assertions.
        const verb = line.split(' ')[0].toUpperCase();
        received.push({ cmd: verb, line });
        const handler = (behavior.onCommand || {})[verb];
        if (verb === 'DATA') {
          inData = true;
          sock.write(handler ? handler() : '354 End data with <CR><LF>.<CR><LF>\r\n');
          continue;
        }
        if (verb === 'QUIT') {
          sock.write(handler ? handler() : '221 Bye\r\n');
          sock.end();
          continue;
        }
        // Default success responses for the verbs we use.
        const defaults = {
          EHLO: () => '250-fake.test\r\n250-SIZE 10240000\r\n250 8BITMIME\r\n',
          HELO: () => '250 fake.test\r\n',
          STARTTLS: () => '454 TLS not available\r\n', // not enabled by default
          AUTH: () => '235 Authentication successful\r\n',
          'MAIL FROM': () => '250 OK\r\n',
          'RCPT TO': () => '250 OK\r\n',
        };
        const respond = handler || defaults[verb];
        sock.write(respond ? respond() : '250 OK\r\n');
      }
    });
    sock.on('error', () => {});
  });
  server.listen(0, '127.0.0.1', () => {
    const port = server.address().port;
    resolve({
      host: `127.0.0.1:${port}`,
      received,
      close: () => new Promise((r) => server.close(() => r())),
    });
  });
});

const makeDigest = () => ({
  title: 'Regress digest: 1 case, 2 runs',
  recipients: ['qa@example.com'],
  html: '<html><body>hi</body></html>',
  project_id: 1,
  window_start: new Date('2026-01-01T00:00:00Z'),
  window_end: new Date('2026-01-01T01:00:00Z'),
  sections: [{ key: 'new_cases', label: 'New cases', count: 1 }],
});

// Pull _sendViaSmtp out of the module via a side channel: since we don't
// export it, we trigger it through deliverDigest with SMTP_HOST set. To
// make that work without a DB we monkey-patch the module's senders.
const runSendViaSmtp = async (smtpHost, digest) => {
  // Reach the function via the deliverDigest path. We need a real DigestLog
  // row to come back; since we're testing the SMTP half, we can pass our
  // own log row.
  // The cleanest way: require the module, then call the inner function
  // through a back-door. Since we deliberately didn't export it, expose it
  // for tests by re-requiring with a side-channel flag.
  process.env.SMTP_HOST = smtpHost;
  const digestModule = require('./digest');
  // The function is module-scoped but reachable via deliverDigest's
  // internal branch. We replicate that branch's effect by reaching
  // through: re-export for the test only.
  if (!digestModule._sendViaSmtp) {
    throw new Error('digest module must export _sendViaSmtp for tests');
  }
  return digestModule._sendViaSmtp(digest, smtpHost);
};

test('_sendViaSmtp: completes EHLO → MAIL FROM → RCPT TO → DATA → QUIT', async () => {
  const srv = await startSmtpServer();
  try {
    const result = await runSendViaSmtp(srv.host, makeDigest());
    assert.equal(result.delivered, true, 'should report delivery success');

    const verbs = srv.received.map((r) => r.cmd);
    assert.equal(verbs[0], 'EHLO', 'first command after banner is EHLO');
    assert.ok(verbs.includes('MAIL'), 'must send MAIL FROM');
    assert.ok(verbs.includes('RCPT'), 'must send RCPT TO');
    assert.ok(verbs.includes('DATA'), 'must send DATA');
    assert.ok(verbs.includes('QUIT'), 'must send QUIT');
    // RCPT TO must come after MAIL FROM, and DATA must come after RCPT TO.
    const idxMail = verbs.indexOf('MAIL');
    const idxRcpt = verbs.indexOf('RCPT');
    const idxData = verbs.indexOf('DATA');
    assert.ok(idxMail < idxRcpt && idxRcpt < idxData, 'commands must be in RFC order');

    const body = srv.received.find((r) => r.cmd === 'DATA_BODY').body;
    assert.ok(body.includes('From: Regress <no-reply@regress.local>'));
    assert.ok(body.includes('To: qa@example.com'));
    assert.ok(body.includes('<html>'));
  } finally {
    delete process.env.SMTP_HOST;
    await srv.close();
  }
});

test('_sendViaSmtp: dot-stuffs body lines that start with a literal dot', async () => {
  // SMTP DATA requires every leading `.` to be doubled. The original
  // client never did this; if the digest body contained `.hidden` it
  // would be interpreted as the message terminator.
  const srv = await startSmtpServer();
  try {
    const digest = makeDigest();
    digest.html = '<html><body>.hidden line</body></html>';
    await runSendViaSmtp(srv.host, digest);
    const body = srv.received.find((r) => r.cmd === 'DATA_BODY').body;
    // The server side un-stuffs, so we should see the original `.hidden`
    // line (and not `..hidden`).
    assert.ok(body.includes('.hidden line'), 'body line should arrive un-stuffed at the server');
  } finally {
    delete process.env.SMTP_HOST;
    await srv.close();
  }
});

test('_sendViaSmtp: rejects when EHLO returns 5xx', async () => {
  const srv = await startSmtpServer({
    onCommand: {
      EHLO: () => '550 EHLO denied\r\n',
    },
  });
  try {
    const result = await runSendViaSmtp(srv.host, makeDigest());
    assert.equal(result.delivered, false, 'must not report delivery on EHLO failure');
    assert.ok(/EHLO/.test(result.error || ''), `error should mention EHLO, got: ${result.error}`);
    // MAIL FROM must NOT have been sent.
    const verbs = srv.received.map((r) => r.cmd);
    assert.ok(!verbs.includes('MAIL'), 'must not send MAIL FROM after EHLO failure');
  } finally {
    delete process.env.SMTP_HOST;
    await srv.close();
  }
});
